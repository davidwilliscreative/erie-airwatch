import type { Metadata } from "next";

import { PageShell } from "@/components/Site";
import { getDashboardData } from "@/lib/data";
import { fmtNumber, pct } from "@/lib/format";

export const metadata: Metadata = { title: "Methodology" };

const H2 = ({ children }: { children: React.ReactNode }) => <h2 className="pt-4 text-xl font-semibold">{children}</h2>;

export default async function MethodologyPage() {
  const data = await getDashboardData();
  const m = data.methodology;
  const th = m.thresholds;
  const ev = m.syntheticEvaluation;
  return (
    <PageShell
      title="Definitions and methodology"
      intro={<>How every number on this site is produced, what it can and cannot tell you, and how it is checked. Algorithm version <strong>{m.algorithmVersion}</strong>.</>}
    >
      <H2>Data source</H2>
      <p>
        {data.mode === "demo"
          ? "This deployment uses synthetic data generated by our own simulator. It exists so the site, the processing pipeline and the review tools can be built and tested before any aviation data licence is in place."
          : "Positions come from a licensed ADS-B data provider. The licence covers continuous collection, storage, derived statistics and public display."}{" "}
        ADS-B is a broadcast that most aircraft transmit with their GPS position and barometric altitude. Receivers do not
        hear every aircraft at every moment, especially close to the ground, so the record always has gaps. We measure
        those gaps and show them beside every trend. <strong>Missing data is never counted as zero activity.</strong>
      </p>

      <H2>What we count</H2>
      <dl className="space-y-4">
        <div>
          <dt className="font-semibold">Zone overflight (observed)</dt>
          <dd className="text-ink-2">
            A track segment between two consecutive position reports that crosses a neighborhood zone. Segments are only
            used when the reports are at most {th.overflight_max_gap_s} s apart; longer gaps are recorded as missing, not
            interpolated. One pass counts once, and re-entering the same zone within {th.overflight_cooldown_s} s is the same pass.
          </dd>
        </div>
        <div>
          <dt className="font-semibold">Candidate circuit (estimated)</dt>
          <dd className="text-ink-2">
            A loop that leaves the runway and returns to the same runway direction within {Math.round(th.circuit_min_s / 60)}–{Math.round(th.circuit_max_s / 60)} minutes,
            stays within {fmtNumber(th.circuit_max_dist_m)} m of the runway and below {fmtNumber(th.circuit_max_agl_ft)} ft above the field,
            and flies a downwind leg ({fmtNumber(th.downwind_min_offset_m)}–{fmtNumber(th.downwind_max_offset_m)} m beside the runway, opposite direction)
            followed by a final approach. Arbitrary loops or orbits away from the runway are not circuits.
          </dd>
        </div>
        <div>
          <dt className="font-semibold">Likely touch-and-go</dt>
          <dd className="text-ink-2">
            An approach to the runway followed by a climbing departure in the same direction, where the aircraft got within
            about {th.tg_max_agl_ft} ft of field elevation, stayed above {th.tg_min_groundspeed_kt} knots, and spent no more than {th.tg_max_duration_s} s over the runway.
            ADS-B cannot prove the wheels touched. A very low go-around looks identical in this data, which is why the label is &ldquo;likely&rdquo; and never &ldquo;confirmed&rdquo;.
          </dd>
        </div>
        <div>
          <dt className="font-semibold">Probable full-stop landing</dt>
          <dd className="text-ink-2">An approach after which groundspeed fell below {th.tg_min_groundspeed_kt} knots, or the track ended on the runway.</dd>
        </div>
        <div>
          <dt className="font-semibold">Repeat activity</dt>
          <dd className="text-ink-2">
            Aircraft with three or more candidate circuits in a local day, published only as a count. Repeated circuits are
            normal flight training and are not evidence of misconduct.
          </dd>
        </div>
      </dl>

      <H2>Altitude</H2>
      <p>
        Aircraft report barometric altitude above mean sea level (MSL). We subtract the field elevation
        ({fmtNumber(data.airport.elevationFt)} ft) to estimate height above the airport. Ground level varies across Erie, so
        this is an estimate with an error of a few hundred feet in places. The published traffic-pattern altitude at Erie is{" "}
        {fmtNumber(data.airport.patternAltitudeFt ?? 0)} ft MSL; it is a procedure for aircraft in the pattern, not a minimum
        legal altitude for all aircraft, and altitude is not a measurement of noise.
      </p>

      <H2>Data-quality labels</H2>
      <p>
        Every finding gets a score from 0 to 1 built from point density, the longest gap in the evidence, altitude
        consistency, closeness to the runway centerline (for runway events) and whether the feed was healthy at the time.
        Scores of {th.high_confidence} and above are labelled high, {th.medium_confidence} and above medium, and anything
        lower is low. Low-quality findings are never published. This label describes the data, not the certainty of the
        classification; see the go-around note above.
      </p>

      <H2>Review and publication</H2>
      <p>
        An administrator reviews findings against the plotted position reports before they are trusted, and can approve,
        reject or flag a finding as needing more data. The site currently publishes{" "}
        {data.policy.mode === "reviewed_only" ? "only reviewer-approved findings" : `reviewer-approved findings plus unreviewed findings with a data-quality score of at least ${data.policy.minConfidence}`}.
        Rejected findings are never published. Every review decision is kept in an audit log.
      </p>

      <H2>How accurate is it?</H2>
      {ev ? (
        <>
          <p>
            Against synthetic traffic with known ground truth (including outages, sparse sampling and ground-level
            dropouts), the current version scores as below. <strong>These figures only show the pipeline works as designed; they say nothing about accuracy on real traffic.</strong>{" "}
            Real-world precision and recall will be measured on at least 100 human-reviewed examples across both runway
            directions before any public launch.
          </p>
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead className="text-left text-ink-3"><tr><th className="py-1 font-normal">Finding</th><th className="font-normal">Precision</th><th className="font-normal">Recall</th><th className="font-normal">False positives</th></tr></thead>
              <tbody className="tabular">
                {Object.values(ev.scores).map((s) => (
                  <tr key={s.kind} className="border-t border-line">
                    <td className="py-1.5">{s.kind.replaceAll("_", " ")}</td><td>{pct(s.precision)}</td><td>{pct(s.recall)}</td><td>{s.fp} of {s.tp + s.fp}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <p className="text-sm text-ink-3">
            Of {ev.non_events.go_arounds} simulated go-arounds, {ev.non_events.go_arounds_labelled_touch_and_go} were labelled likely touch-and-go:
            very low go-arounds cannot be told apart from touch-and-goes with position data alone.
          </p>
        </>
      ) : <p>Validation results are published with each methodology version.</p>}

      <H2>Thresholds (version {m.algorithmVersion})</H2>
      <div className="overflow-x-auto rounded-lg border border-line bg-surface">
        <table className="w-full text-sm">
          <tbody className="tabular">
            {Object.entries(th).map(([k, v]) => <tr key={k} className="border-t border-line first:border-0"><td className="px-3 py-1.5 font-mono text-xs">{k}</td><td className="px-3 text-right">{v}</td></tr>)}
          </tbody>
        </table>
      </div>

      <H2>Changelog</H2>
      <ul className="list-disc pl-5">
        <li><strong>1.0.0</strong>: initial definitions for overflights, candidate circuits, likely touch-and-go, probable full stops and low approaches. When definitions change, history is recomputed and reports are reissued with a new version.</li>
      </ul>
    </PageShell>
  );
}
